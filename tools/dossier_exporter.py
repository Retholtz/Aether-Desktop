import os
import re
import time
import subprocess
from typing import Dict, Any, List, Optional

from core.paths import user_data_path

DOSSIER_DIR = user_data_path("data", "dossiers")
LATEST_DOSSIER_LINK = user_data_path("data", "scratchpad", "latest_dossier.md")


def _safe_dossier_path(filename: str) -> Optional[str]:
    """Resolves a dossier filename strictly inside DOSSIER_DIR, preventing traversal."""
    if not filename or not isinstance(filename, str):
        return None
    clean_name = os.path.basename(filename.strip())
    if not clean_name.lower().endswith(".md"):
        return None
    base_dir = os.path.abspath(DOSSIER_DIR)
    candidate = os.path.abspath(os.path.join(base_dir, clean_name))
    if not candidate.startswith(base_dir + os.sep):
        return None
    return candidate


def _parse_dossier_summary(file_path: str, filename: str) -> Dict[str, Any]:
    """Extracts title, date/time, category, and preview snippet from a dossier Markdown file."""
    title = os.path.splitext(filename)[0]
    m_date = re.match(r"^(\d{4})(\d{2})(\d{2})_(\d{2})(\d{2})(\d{2})_(.+?)\.md$", filename)
    date_str = ""
    time_str = ""
    if m_date:
        date_str = f"{m_date.group(1)}-{m_date.group(2)}-{m_date.group(3)}"
        time_str = f"{m_date.group(4)}:{m_date.group(5)}:{m_date.group(6)}"
        title = m_date.group(7).replace("_", " ").strip()

    category = "general"
    preview = ""
    char_count = 0
    word_count = 0
    mtime = 0.0

    try:
        st = os.stat(file_path)
        mtime = st.st_mtime
        if not date_str:
            lt = time.localtime(mtime)
            date_str = time.strftime("%Y-%m-%d", lt)
            time_str = time.strftime("%H:%M:%S", lt)

        with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
            raw = f.read()
        char_count = len(raw)
        word_count = len(raw.split())

        for line in raw.splitlines()[:25]:
            s = line.strip()
            if not s:
                continue
            if s.startswith("# ") and title == m_date.group(7).replace("_", " ").strip() if m_date else s.startswith("# "):
                title = s[2:].strip()
            elif s.lower().startswith("*category:") and s.endswith("*"):
                category = s[10:-1].strip() or "general"
            elif s.startswith("*Generated by "):
                continue
            elif s in ("---", "***", "___"):
                continue
            elif not preview and not s.startswith("#"):
                preview = re.sub(r"[*_`#>\[\]]", "", s)[:140]
    except Exception:
        pass

    return {
        "filename": filename,
        "title": title,
        "category": category,
        "date": date_str,
        "time": time_str,
        "preview": preview,
        "char_count": char_count,
        "word_count": word_count,
        "mtime": mtime,
    }


def list_dossiers(query: Optional[str] = None) -> List[Dict[str, Any]]:
    """Lists saved Markdown dossiers from data/dossiers/ sorted newest-first."""
    if not os.path.isdir(DOSSIER_DIR):
        return []
    q = (query or "").strip().lower()
    items: List[Dict[str, Any]] = []
    for fname in os.listdir(DOSSIER_DIR):
        if not fname.lower().endswith(".md"):
            continue
        fpath = os.path.join(DOSSIER_DIR, fname)
        if not os.path.isfile(fpath):
            continue
        meta = _parse_dossier_summary(fpath, fname)
        if q:
            haystack = f"{meta['title']} {meta['category']} {meta['filename']} {meta['preview']}".lower()
            if q not in haystack:
                try:
                    with open(fpath, "r", encoding="utf-8", errors="ignore") as f:
                        if q not in f.read(32768).lower():
                            continue
                except Exception:
                    continue
        items.append(meta)

    items.sort(key=lambda d: (d.get("date", ""), d.get("time", ""), d.get("mtime", 0)), reverse=True)
    return items


def get_dossier_details(filename: str) -> Dict[str, Any]:
    """Reads a dossier file and returns metadata, raw Markdown, and Word/Docs-styled HTML."""
    fpath = _safe_dossier_path(filename)
    if not fpath or not os.path.isfile(fpath):
        return {"status": "error", "message": "Dossier file not found."}
    try:
        with open(fpath, "r", encoding="utf-8") as f:
            content = f.read()
        meta = _parse_dossier_summary(fpath, os.path.basename(fpath))
        from tools.clipboard import markdown_to_html_for_clipboard
        rendered_html = markdown_to_html_for_clipboard(content)
        return {
            "status": "success",
            "dossier": {
                **meta,
                "file_path": fpath,
                "content_markdown": content,
                "rendered_html": rendered_html,
            },
        }
    except Exception as e:
        return {"status": "error", "message": str(e)}


def delete_dossier_file(filename: str) -> Dict[str, Any]:
    """Deletes a saved dossier file from data/dossiers/."""
    fpath = _safe_dossier_path(filename)
    if not fpath or not os.path.isfile(fpath):
        return {"status": "error", "message": "Dossier file not found."}
    try:
        os.remove(fpath)
        return {"status": "success", "filename": os.path.basename(fpath)}
    except Exception as e:
        return {"status": "error", "message": str(e)}

def _sanitize_filename(name: str) -> str:
    """Cleans a string for safe use as a Windows/POSIX filename."""
    cleaned = re.sub(r'[\\/*?:"<>| ]', "_", name.strip())
    return cleaned[:64].strip("_")

def export_research_dossier(
    title: str,
    content_markdown: str,
    category: str = "research",
    open_immediately: bool = False
) -> Dict[str, Any]:
    """
    Saves a comprehensive, structured Markdown dossier or report to disk.
    Use this tool whenever you gather detailed research, family trees, public records, 
    or multi-step analysis that is too lengthy to speak entirely aloud.
    
    Args:
        title: Short descriptive title for the document (e.g., 'Stanley_Orlop_Genealogy')
        content_markdown: Full structured Markdown content with headers, bullet points, and tables.
        category: Sub-category ('genealogy', 'technical', 'system_audit', 'general')
        open_immediately: Whether to pop the saved file open in the default system viewer.
    """
    os.makedirs(DOSSIER_DIR, exist_ok=True)
    os.makedirs(os.path.dirname(LATEST_DOSSIER_LINK), exist_ok=True)

    date_str = time.strftime("%Y%m%d_%H%M%S")
    safe_title = _sanitize_filename(title)
    filename = f"{date_str}_{safe_title}.md"
    file_path = os.path.join(DOSSIER_DIR, filename)

    # Format document header
    header = f"""# {title}
*Generated by Aether Desktop Agent • {time.strftime('%Y-%m-%d %H:%M:%S')}*
*Category: {category}*

---

"""
    full_content = header + content_markdown.strip() + "\n"

    try:
        # Write permanent timestamped dossier
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(full_content)

        # Write or overwrite scratchpad pointer
        with open(LATEST_DOSSIER_LINK, "w", encoding="utf-8") as f:
            f.write(full_content)

        # Also register the exported dossier in the session manifest index for instant historical lookup
        try:
            from core.manifest_indexer import index_manifest_card
            abs_dossier_path = os.path.abspath(file_path)
            card = {
                "session_id": f"dossier_{date_str}_{safe_title[:24]}",
                "date": time.strftime("%Y-%m-%d"),
                "timestamp": time.time(),
                "topics_discussed": [f"Research Dossier / Guide: {title} ({category})"],
                "actions_executed": [f"Exported Markdown dossier to {file_path}"],
                "unresolved_questions": [],
                "key_entities": [title, filename, file_path]
            }
            index_manifest_card(card, abs_dossier_path)
        except Exception as idx_err:
            print(f"[DEBUG] [DOSSIER] Manifest index note: {idx_err}")

        # Optional open in default editor
        if open_immediately:
            try:
                os.startfile(file_path)
            except Exception as launch_err:
                print(f"[WARN] [DOSSIER] Could not auto-open file: {launch_err}")

        print(f"[INFO] [DOSSIER] Successfully exported research dossier to {file_path}")
        return {
            "status": "success",
            "file_path": os.path.abspath(file_path),
            "filename": filename,
            "char_count": len(full_content),
            "directive": (
                "File written successfully. Deliver a concise 2-3 sentence verbal summary of the "
                "findings over voice and mention that the complete details have been saved to the dossier."
            )
        }
    except Exception as e:
        print(f"[ERROR] [DOSSIER] Failed to write research dossier: {e}")
        return {
            "status": "error",
            "message": str(e)
        }
